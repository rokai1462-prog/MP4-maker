#!/usr/bin/env node
/*
  Build the house "word-by-word highlight" captions for one video.

  Usage (from the space-videos folder):
    node tools/build-captions.mjs videos/<name>

  Reads   videos/<name>/script/words.json  — [{ "text": "Saturn's", "start": 0.32, "end": 0.71 }, ...]
          (absolute seconds on the video's timeline; from the voiceover's word timings)
  Writes  videos/<name>/compositions/captions.html

  Style: 3–5 words on screen at a time; the whole group appears, and each word lights up
  warm gold while it is spoken, then settles to white. Words wrapped in *asterisks* in
  words.json stay gold after they are spoken (key words).
*/
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node tools/build-captions.mjs videos/<name>");
  process.exit(1);
}
const wordsPath = path.join(dir, "script", "words.json");
const outPath = path.join(dir, "compositions", "captions.html");
const words = JSON.parse(fs.readFileSync(wordsPath, "utf8"))
  .map((w) => ({ ...w, text: String(w.text).trim() }))
  .filter((w) => w.text && !/^[♪�]+$/.test(w.text));

const MAX_WORDS = 4; // a group wraps to at most two lines in the 660 px caption column
const PAUSE_BREAK = 0.15;
const groups = [];
let cur = [];
for (let i = 0; i < words.length; i++) {
  const w = words[i];
  cur.push(w);
  const next = words[i + 1];
  const sentenceEnd = /[.!?…]["”')]*$/.test(w.text.replace(/\*/g, ""));
  const pause = next ? next.start - w.end >= PAUSE_BREAK : true;
  const commaBreak = /[,;:—]$/.test(w.text.replace(/\*/g, "")) && cur.length >= 3;
  if (!next || cur.length >= MAX_WORDS || sentenceEnd || pause || commaBreak) {
    groups.push(cur);
    cur = [];
  }
}

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
let html = "";
const timing = [];
groups.forEach((g, gi) => {
  const id = `cap-${String(gi + 1).padStart(2, "0")}`;
  const prevEnd = gi > 0 ? groups[gi - 1].at(-1).end : 0;
  const nextStart = gi < groups.length - 1 ? groups[gi + 1][0].start : Infinity;
  const open = Math.max(gi === 0 ? 0.15 : prevEnd, g[0].start - 0.1);
  const close = Math.min(nextStart, g.at(-1).end + 0.35);
  const spans = g
    .map((w, wi) => {
      const key = /^\*.*\*[.,!?;:]*$/.test(w.text);
      const text = esc(w.text.replace(/\*/g, ""));
      return `<span id="${id}-w${wi}" class="w${key ? " key" : ""}" data-s="${w.start.toFixed(3)}" data-e="${w.end.toFixed(3)}">${text}</span>`;
    })
    .join(" ");
  html += `    <div id="${id}" class="cap-group" data-open="${open.toFixed(3)}" data-close="${close.toFixed(3)}"><span class="cap-line">${spans}</span></div>\n`;
  timing.push([open, close]);
});

const out = `<template>
  <!-- GENERATED by tools/build-captions.mjs from script/words.json — edit words.json, then re-run. -->
  <style>
    #root {
      position: absolute;
      inset: 0;
    }
    .cap-group {
      position: absolute;
      left: 120px; /* shared TikTok/Reels/Shorts safe area below y 840: x 120..780 */
      right: 300px;
      bottom: 680px; /* bottom edge at y 1240, just above the 1248 px safe line */
      text-align: center;
      overflow: visible;
      opacity: 0;
      visibility: hidden;
    }
    .cap-line {
      display: inline-block;
      max-width: 660px;
      font-family: var(--sv-font-body);
      font-weight: 800;
      font-size: 68px;
      line-height: 1.15;
      letter-spacing: -0.01em;
      text-shadow: 0 3px 22px rgba(0, 0, 0, 0.9);
    }
    .cap-line .w {
      display: inline-block;
      margin: 0 0.13em;
      color: rgba(255, 255, 255, 0.55);
    }
  </style>
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920">
${html}  </div>
  <script>
    (function () {
      const tl = gsap.timeline({ paused: true });
      const GOLD = "#ffc37a";
      document.querySelectorAll("#root .cap-group").forEach((g) => {
        const open = parseFloat(g.dataset.open);
        const close = parseFloat(g.dataset.close);
        const line = g.querySelector(".cap-line");
        tl.set(g, { visibility: "visible" }, open);
        tl.fromTo(g, { opacity: 0, y: 16 }, { opacity: 1, y: 0, duration: 0.18, ease: "power2.out" }, open);
        g.querySelectorAll(".w").forEach((w) => {
          const s = parseFloat(w.dataset.s);
          const e = parseFloat(w.dataset.e);
          tl.to(w, { color: GOLD, scale: 1.08, duration: 0.08, ease: "power1.out" }, s);
          const settle = w.classList.contains("key") ? GOLD : "#ffffff";
          tl.to(w, { color: settle, scale: 1, duration: 0.15, ease: "power1.inOut" }, Math.max(s + 0.08, e));
        });
        tl.to(g, { opacity: 0, duration: 0.12, ease: "power2.in" }, close - 0.12);
        tl.set(g, { opacity: 0, visibility: "hidden" }, close);
      });
      window.__timelines["captions"] = tl;
    })();
  </script>
</template>
`;
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath}: ${groups.length} caption groups from ${words.length} words.`);
